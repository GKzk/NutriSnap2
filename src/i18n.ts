export function getMealTypeText(lang: Language, type: MealType): string {
  return translations[lang][type];
}

export function getWorkLabel(lang: Language, work: WorkActivity): string {
  const t = translations[lang];
  if (work === 'sedentary') return t.workSedentary;
  if (work === 'moderate') return t.workModerate;
  return t.workActive;
}

export function getFreqLabel(lang: Language, freq: SportsFrequency): string {
  const t = translations[lang];
  if (freq === '1-2') return t.freq1_2;
  if (freq === '3-4') return t.freq3_4;
  if (freq === '5+') return t.freq5plus;
  return t.freqNone;
}
